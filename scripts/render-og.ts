/**
 * Regenerates src/web/ogImagePng.ts (the PNG social preview served at
 * /assets/og.png) from ogImageSvg in src/web/assets.ts.
 *
 *   npm i --no-save @resvg/resvg-js   # renderer, not a project dependency
 *   npx tsx scripts/render-og.ts
 *
 * Falls back to the rsvg-convert CLI when resvg-js is not installed. If
 * ImageMagick is on PATH the result is quantised to 64 colours to keep the
 * embedded base64 small.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ogImageSvg } from "../src/web/assets";

function render(svg: string): Buffer {
  try {
    type Renderer = new (svg: string, opts: unknown) => { render(): { asPng(): Uint8Array } };
    const { Resvg } = require("@resvg/resvg-js") as { Resvg: Renderer };
    return Buffer.from(new Resvg(svg, { fitTo: { mode: "width", value: 1200 } }).render().asPng());
  } catch {
    const dir = mkdtempSync(join(tmpdir(), "og-"));
    const input = join(dir, "og.svg");
    const output = join(dir, "og.png");
    writeFileSync(input, svg);
    execFileSync("rsvg-convert", ["-w", "1200", "-h", "630", "-o", output, input]);
    return readFileSync(output);
  }
}

function quantise(png: Buffer): Buffer {
  try {
    return execFileSync("magick", ["png:-", "-strip", "-colors", "64", "PNG8:-"], { input: png });
  } catch {
    return png;
  }
}

const png = quantise(render(ogImageSvg));
const out = join(__dirname, "..", "src", "web", "ogImagePng.ts");
writeFileSync(
  out,
  `/* Generated by scripts/render-og.ts from ogImageSvg in ./assets. Do not edit by hand. */\n` +
    `export const ogImagePng = Buffer.from(\n  "${png.toString("base64")}",\n  "base64",\n);\n`,
);
console.log(`wrote ${out} (${png.length} bytes PNG)`);
